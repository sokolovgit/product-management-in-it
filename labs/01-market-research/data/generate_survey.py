def pick(rng: random.Random, dist: dict[str, float]) -> str:
    return rng.choices(list(dist), weights=list(dist.values()))[0]


def multi(rng: random.Random, probs: dict[str, float]) -> str:
    chosen = [k for k, p in probs.items() if rng.random() < p]
    if not chosen:
        chosen = [max(probs, key=probs.get)]
    return "; ".join(chosen)


def likert(rng: random.Random, mean: float) -> int:
    return max(1, min(5, round(rng.gauss(mean, 0.8))))


def respondent(rng: random.Random, seg: str, open_pool: list[tuple[str, str]]) -> dict:
    s = SEGMENTS[seg]
    students = pick(rng, s["students"])
    load = {"1–5": 0, "6–10": 1, "11–20": 2, "21+": 3}[students]
    admin = pick(rng, s["admin"])
    admin_level = {"Менше 1 год": 0, "1–2 год": 1, "3–5 год": 2, "Понад 5 год": 3}[
        admin
    ]
    pain = 2.9 + 0.35 * load + 0.2 * admin_level

    q2 = (
        "Так"
        if rng.random() < 0.35 + 0.15 * load
        else ("Іноді" if rng.random() < 0.85 else "Ні")
    )
    q7 = pick(
        rng, {"Щодня": 1 + load, "Кілька разів на тиждень": 4 + load, "Рідко": 4 - load}
    )
    q11 = pick(
        rng,
        {
            "Жодного разу": max(0.5, 3 - load),
            "1–2 рази": 5,
            "3–5 разів": 1 + load,
            "Понад 5 разів": 0.3 * load,
        },
    )
    subjects = s["subjects"][0] if rng.random() < 0.75 else "; ".join(s["subjects"])
    tools = multi(rng, s["tools"])
    satisfied = likert(rng, 4.6 - pain * 0.55)
    text, theme = (
        open_pool.pop(rng.randrange(len(open_pool))) if open_pool else ("", "")
    )

    return {
        "Q1": "Так",
        "Q2": q2,
        "Q3": pick(rng, s["age"]),
        "Q4": subjects,
        "Q5": students,
        "Q6": pick(rng, s["format"]),
        "Q7": q7,
        "Q8": tools,
        "Q9": admin,
        "Q10": multi(rng, s["pay"]),
        "Q11": q11,
        "Q12": satisfied,
        "Q13": likert(rng, pain + 0.4),
        "Q14": likert(rng, pain + (0.3 if q11 != "Жодного разу" else -0.8)),
        "Q15": likert(rng, pain - 0.2),
        "Q16": likert(rng, pain - (0.1 if seg in ("teacher", "music") else 0.9)),
        "Q17": pick(rng, s["wtp"]),
        "Q18": pick(rng, s["feature"]),
        "Q19": text,
        "theme": theme,
    }


def main() -> None:
    rng = random.Random(SEED)
    segments = [seg for seg, s in SEGMENTS.items() for _ in range(s["weight"])]
    rng.shuffle(segments)
    pools = {seg: list(items) for seg, items in OPEN.items()}

    rows = [respondent(rng, seg, pools[seg]) for seg in segments]
    # Нецільові: не займаються репетиторством, опитування для них завершується на Q1.
    for pos in rng.sample(range(len(rows) + 4), 4):
        rows.insert(pos, {"Q1": "Ні"})

    with OUT.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=COLUMNS, restval="")
        writer.writeheader()
        writer.writerows(rows)
    print(f"{OUT.name}: {len(rows)} відповідей")


if __name__ == "__main__":
    main()
